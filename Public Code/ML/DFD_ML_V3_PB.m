        speed = Tachometer_rpm * 1.666667e-02;

        % Compute the fault frequency bands.
        [FB, info] = bearingFaultBands(speed, 8, 6.750000e+00, 2.905000e+01, 0, ...
        	'Sidebands', [0 1], 'Folding', true);

        idx = true(8, 1);

        % Apply the filter to the fault bands.
        FB_filtered = FB(idx, :);
        info_filtered = struct;
        info_filtered.Centers = info.Centers(idx);
        info_filtered.Labels = info.Labels(idx);
        info_filtered.FaultGroups = info.FaultGroups(idx);

        % Compute spectral fault band metrics.
        sd = Vibration_ps.SpectrumData;
        w = Vibration_ps.Frequency;

        metrics = faultBandMetrics(sd, w, FB_filtered(1:8,:));

        % Extract computed features.
        metricsNames = {'PeakAmplitude6','BandPower6','PeakAmplitude7','BandPower7'};
        featureNames = {'PeakAmp6','BandPower6','PeakAmp7','BandPower7'};
        Vibration_ps_bearing = metrics(:,metricsNames);
        Vibration_ps_bearing = renamevars(Vibration_ps_bearing, metricsNames, featureNames);
    catch
        % Package computed features into a table.
        featureValues = NaN(1,4);
        featureNames = ["PeakAmp6","BandPower6","PeakAmp7","BandPower7"];
        Vibration_ps_bearing = array2table(featureValues,'VariableNames',featureNames);
    end

    % Append computed results to the member table.
    memberResult = [memberResult, ...
        table({Vibration_ps_bearing},'VariableNames',{'Vibration_ps_bearing'})]; %#ok<AGROW>

    %% Write all the results for the current member to the ensemble.
    writeToLastMemberRead(outputEnsemble,memberResult)
end

