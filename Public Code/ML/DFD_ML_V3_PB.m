% Create output ensemble.
outputEnsemble = workspaceEnsemble(inputData,'DataVariables',["Vibration";"Tachometer"],'ConditionVariables',"faultCode");

% Reset the ensemble to read from the beginning of the ensemble.
reset(outputEnsemble);

% Append new signal or feature names to DataVariables.
outputEnsemble.DataVariables = unique([outputEnsemble.DataVariables;"Tachometer_rpm";"Vibration_ps";"Vibration_ps_bearing"],'stable');

% Set SelectedVariables to select variables to read from the ensemble.
outputEnsemble.SelectedVariables = ["Vibration","Tachometer"];

% Loop through all ensemble members to read and write data.
while hasdata(outputEnsemble)
    % Read one member.
    member = read(outputEnsemble);

    % Get all input variables.
    Vibration = readMemberData(member,"Vibration",["Time","Vibration"]);
    Tachometer = readMemberData(member,"Tachometer",["Time","Tachometer"]);

    % Initialize a table to store results.
    memberResult = table;

    %% TSA
    try
        % Convert any datetime data to duration.
        if isdatetime(Vibration.Time)
            tVib = Vibration.Time - Vibration.Time(1);
        else
            tVib = Vibration.Time;
        end

        % Compute tacho pulse times in units of seconds.
        tNumeric = time2num(Tachometer.Time,"seconds");
        Fs = effectivefs(tNumeric);
        [~,~,tp] = tachorpm(Tachometer.Tachometer,Fs,'PulsesPerRev',1,'FitType','linear');
        tp = tp + tNumeric(1);

        % Compute the time-synchronous average and the nominal rpm.
        [xTsa,tTsa,~,rpm] = tsa(Vibration.Vibration,tVib,tp, ...
            'Method','linear','PulsesPerRotation',1,'NumRotations',1);

        % Store the nominal rpm as a condition variable.
        Tachometer_rpm = rpm;
    catch
        % Store the nominal rpm as a condition variable.
        Tachometer_rpm = NaN;
    end

    % Append computed results to the member table.
    memberResult = [memberResult, ...
        table(Tachometer_rpm,'VariableNames',{'Tachometer_rpm'})]; %#ok<AGROW>

    %% PowerSpectrum
    try
        % Get units to use in computed spectrum.
        tuReal = "seconds";

        % Compute effective sampling rate.
        tNumeric = time2num(Vibration.Time,tuReal);
        [Fs,irregular] = effectivefs(tNumeric);
        Ts = 1/Fs;

        % Resample non-uniform signals.
        x_raw = Vibration.Vibration;
        if irregular
            x = resample(x_raw,tNumeric,Fs,'linear');
        else
            x = x_raw;
        end

        % Set Welch spectrum parameters.
        L = fix(length(x)/4.5);
        noverlap = fix(L*50/100);
        win = hamming(L);

        % Compute the power spectrum.
        f = linspace(0,10000,1000);
        f = f*funitconv('Hz','cycles/TimeUnit','seconds');
        [ps,f] = pwelch(x,win,noverlap,f(:),Fs);
        ps = 2*ps;
        w = 2*pi*f;

        % Convert frequency unit.
        factor = funitconv('rad/TimeUnit', 'Hz', 'seconds');
        w = factor*w;
        Fs = 2*pi*factor*Fs;

        % Remove frequencies above Nyquist frequency.
        I = w<=(Fs/2+1e4*eps);
        w = w(I);
        ps = ps(I);

        % Configure the computed spectrum.
        ps = table(w, ps, 'VariableNames', {'Frequency', 'SpectrumData'});
        ps.Properties.VariableUnits = {'Hz', ''};
        ps = addprop(ps, {'SampleFrequency'}, {'table'});
        ps.Properties.CustomProperties.SampleFrequency = Fs;
        Vibration_ps = ps;
    catch
        Vibration_ps = table(NaN, NaN, 'VariableNames', {'Frequency', 'SpectrumData'});
    end

    % Append computed results to the member table.
    memberResult = [memberResult, ...
        table({Vibration_ps},'VariableNames',{'Vibration_ps'})]; %#ok<AGROW>

    %% BearingFaultsFeatures
    try
